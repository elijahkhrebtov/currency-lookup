import { test, expect, openConverter } from './fixtures'

async function openCalculator(page) {
  await page.goto('/')
  await openConverter(page)
  await page.getByRole('tab', { name: 'Calculator', exact: true }).click()
  return page.getByRole('tabpanel', { name: 'Calculator', exact: true })
}
async function press(calculator, ...keys) {
  for (const name of keys) await calculator.getByRole('button', { name, exact: true }).click()
}

test('calculator uses buttons for decimals, arithmetic, signs, clearing, and backspace', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 320, height: 568 })
  const calculator = await openCalculator(page)
  const display = calculator.getByLabel('Calculator display')
  await expect(calculator.locator('input, textarea, [contenteditable="true"]')).toHaveCount(0)
  await expect(display).toHaveText('0')
  await press(calculator, '0', 'Decimal point', '1', 'Add', '0', 'Decimal point', '2', 'Equals')
  await expect(display).toHaveText('0.3')
  await press(calculator, 'Multiply', '1', '0', 'Equals')
  await expect(display).toHaveText('3')
  await press(calculator, 'Divide', '2', 'Equals', 'Change sign')
  await expect(display).toHaveText('−1.5')
  await press(calculator, 'Change sign', 'Subtract', '0', 'Decimal point', '5', 'Equals')
  await expect(display).toHaveText('1')
  await press(calculator, 'Clear all', '1', '2', '3', 'Backspace', 'Add', '9', 'Clear entry', '2', 'Equals')
  await expect(display).toHaveText('14')
  await press(calculator, 'Clear all', '8', 'Add', '9', 'Clear all', '2', 'Equals')
  await expect(display).toHaveText('2')
  await expect(page.getByRole('tab', { name: 'Converter', exact: true })).toHaveAttribute('aria-selected', 'false')
  await page.screenshot({ path: `/tmp/currency-calculator-${testInfo.project.name}.png` })
  expect(await calculator.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  const tabBounds = await page.getByRole('tab', { name: 'Calculator' }).boundingBox()
  expect(tabBounds.y + tabBounds.height).toBeLessThanOrEqual(568)
})

test('pending calculator state and converter edits survive tab switches and closing the sidebar', async ({ page }) => {
  const calculator = await openCalculator(page)
  const display = calculator.getByLabel('Calculator display')
  await press(calculator, '1', '2', 'Add', 'Change sign', '3', 'Decimal point', '5')
  await expect(display).toHaveText('−3.5')
  await page.getByRole('tab', { name: 'Converter', exact: true }).click()
  await page.getByLabel('USD amount').fill('246.8')
  await expect(calculator).toBeHidden()
  await page.getByRole('tab', { name: 'Calculator', exact: true }).click()
  await expect(display).toHaveText('−3.5')
  await page.getByRole('button', { name: 'Close sidebar' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Open sidebar' }).click()
  await expect(page.getByRole('tab', { name: 'Calculator', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(display).toHaveText('−3.5')
  await press(calculator, 'Equals')
  await expect(display).toHaveText('8.5')
  await press(calculator, 'Equals')
  await expect(display).toHaveText('5')
  await page.getByRole('tab', { name: 'Converter', exact: true }).click()
  await expect(page.getByLabel('USD amount')).toHaveValue('246.8')
  // Tab-key focus skips the hidden calculator and arrow keys select the other tool.
  await page.getByRole('tab', { name: 'Converter', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Calculator', exact: true })).toBeFocused()
  await expect(display).toHaveText('5')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Close sidebar' })).toBeFocused()
  await page.getByRole('button', { name: 'Close sidebar' }).focus()
  await page.keyboard.press('Tab')
  await expect(calculator.getByRole('region', { name: 'Recent results', exact: true }).getByRole('button').first()).toBeFocused()
})

test('division by zero is recoverable without native input', async ({ page }) => {
  const calculator = await openCalculator(page)
  const display = calculator.getByLabel('Calculator display')
  await press(calculator, '9', 'Divide', '0', 'Equals')
  await expect(display).toHaveText('Error')
  await expect(calculator.getByLabel('Calculation', { exact: true })).toHaveText('Cannot divide by zero')
  await press(calculator, 'Clear entry', '4', 'Divide', '2', 'Equals')
  await expect(display).toHaveText('2')
})

const RESULTS_KEY = 'pocket-calculator.results.v1'

test('each equals saves a result locally, including duplicates, and survives reloading', async ({ page }) => {
  const calculator = await openCalculator(page)
  const recents = calculator.getByRole('region', { name: 'Recent results', exact: true })
  await press(calculator, '7', 'Equals', 'Equals')
  await expect(recents.getByRole('button')).toHaveCount(2)
  await press(calculator, 'Add', '3', 'Multiply', '2')
  await expect(recents.getByRole('button')).toHaveCount(2)
  await press(calculator, 'Equals')
  await expect(recents.getByRole('button')).toHaveCount(3)
  await press(calculator, 'Divide', '0', 'Equals')
  await expect(calculator.getByLabel('Calculator display')).toHaveText('Error')
  await expect(recents.getByRole('button')).toHaveCount(3)
  await press(calculator, 'Clear all')
  await expect(recents.getByRole('button')).toHaveCount(3)
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).map(result => result.value), RESULTS_KEY)).toEqual(['20', '7', '7'])
  await page.reload()
  await openConverter(page)
  await page.getByRole('tab', { name: 'Calculator', exact: true }).click()
  await expect(recents.getByRole('button')).toHaveCount(3)
  await expect(recents.getByRole('button').first()).toHaveAccessibleName('Use result 20')
  await expect(calculator.getByLabel('Calculator display')).toHaveText('0')
})

test('recent results stay capped, scroll above stationary controls, and replace pending operands', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 320, height: 800 })
  await page.addInitScript(key => {
    localStorage.setItem(key, JSON.stringify(Array.from({ length: 20 }, (_, i) => ({ value: String(20 - i), expression: `${20 - i} =` }))))
  }, RESULTS_KEY)
  const calculator = await openCalculator(page)
  const recents = calculator.getByRole('region', { name: 'Recent results', exact: true })
  await press(calculator, '2', '1', 'Equals')
  await expect(recents.getByRole('button')).toHaveCount(20)
  await expect(recents.getByRole('button').first()).toHaveAccessibleName('Use result 21')
  await expect(recents.getByRole('button').last()).toHaveAccessibleName('Use result 2')
  const before = await calculator.locator('.calculator-keypad').boundingBox()
  const list = calculator.locator('.calculator-results')
  await list.evaluate(element => { element.scrollTop = element.scrollHeight })
  expect(await list.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  expect(await calculator.locator('.calculator-keypad').boundingBox()).toEqual(before)
  await press(calculator, 'Clear all', '8', 'Add', '9')
  await recents.getByRole('button', { name: 'Use result 2', exact: true }).click()
  await expect(calculator.getByLabel('Calculator display')).toHaveText('2')
  await expect(calculator.getByRole('button', { name: 'Add', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await press(calculator, 'Equals')
  await expect(calculator.getByLabel('Calculator display')).toHaveText('10')
  await expect(recents.getByRole('button').first()).toHaveAccessibleName('Use result 10')
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).length, RESULTS_KEY)).toBe(20)
  expect(await list.evaluate(element => element.scrollTop)).toBe(0)
  await page.screenshot({ path: `/tmp/currency-calculator-history-${testInfo.project.name}.png` })
})

test('negative decimal history values replace the entry without replaying an old operation', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, JSON.stringify([{ value: '-3.5', expression: '−7 ÷ 2 =' }])), RESULTS_KEY)
  const calculator = await openCalculator(page)
  const saved = calculator.getByRole('button', { name: 'Use result −3.5', exact: true })
  await press(calculator, '1', '2', 'Multiply')
  await saved.click()
  await press(calculator, 'Equals')
  await expect(calculator.getByLabel('Calculator display')).toHaveText('−42')
  await saved.click()
  await press(calculator, 'Equals')
  await expect(calculator.getByLabel('Calculator display')).toHaveText('−3.5')
  await expect(calculator.getByRole('region', { name: 'Recent results', exact: true }).getByRole('button')).toHaveCount(3)
})

test('corrupt or unavailable local storage does not break the calculator', async ({ page }) => {
  await page.addInitScript(key => {
    localStorage.setItem(key, '{broken')
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (storageKey, value) {
      if (storageKey === key) throw new DOMException('Storage unavailable', 'QuotaExceededError')
      return original.call(this, storageKey, value)
    }
  }, RESULTS_KEY)
  const calculator = await openCalculator(page)
  await expect(calculator.getByText('Results appear here after =.', { exact: true })).toBeVisible()
  await press(calculator, '2', 'Add', '3', 'Equals')
  await expect(calculator.getByLabel('Calculator display')).toHaveText('5')
  await expect(calculator.getByRole('status').filter({ hasText: "History couldn't be saved" })).toBeVisible()
  await expect(calculator.getByRole('button', { name: 'Use result 5', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close sidebar' }).click()
  await page.getByRole('button', { name: 'Open sidebar' }).click()
  await expect(calculator.getByRole('button', { name: 'Use result 5', exact: true })).toBeVisible()
})
