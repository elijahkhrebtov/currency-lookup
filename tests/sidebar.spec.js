import { test, expect, openConverter, store } from './fixtures'

async function swipe(page, context, mobile, from, to, hold = 0) {
  if (mobile) {
    const cdp = await context.newCDPSession(page)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: from.x, y: from.y }] })
    for (let step = 1; step <= 12; step++) {
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: from.x + (to.x - from.x) * step / 12, y: from.y + (to.y - from.y) * step / 12 }] })
    }
    if (hold) await page.waitForTimeout(hold)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await cdp.detach()
  } else {
    await page.mouse.move(from.x, from.y)
    await page.mouse.down()
    await page.mouse.move(to.x, to.y, { steps: 12 })
    if (hold) await page.waitForTimeout(hold)
    await page.mouse.up()
  }
}

test('budget is the main screen and the sidebar preserves converter and calendar state', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 320, height: 700 })
  await page.clock.setFixedTime(new Date('2026-11-03T12:00:00Z'))
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'New entry', exact: true })).toBeEnabled()
  expect(store(page).currencyReads).toBe(0)
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await page.getByRole('button', { name: 'Nov 4, 2026', exact: true }).click()
  await page.screenshot({ path: `/tmp/currency-sidebar-${testInfo.project.name}-budget.png` })
  await openConverter(page)
  await expect(page.getByRole('tab')).toHaveCount(2)
  await expect(page.getByLabel('USD amount')).toHaveValue('100')
  await page.getByLabel('USD amount').fill('220.12345678')
  await page.getByLabel('Move EUR up').click()
  await page.getByLabel('Change EUR currency').click()
  await expect(page.getByLabel('Search currencies')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Tools', exact: true })).toBeVisible()
  await expect(page.getByLabel('Change EUR currency')).toBeFocused()
  await page.screenshot({ path: `/tmp/currency-sidebar-${testInfo.project.name}-converter.png` })
  expect(await page.getByRole('tabpanel', { name: 'Converter', exact: true }).evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Open sidebar', exact: true })).toBeFocused()
  await expect(page.getByRole('button', { name: 'Nov 4, 2026', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await openConverter(page)
  await expect(page.getByLabel('USD amount')).toHaveValue('220.12345678')
  await expect(page.locator('.currency-code').first()).toHaveText('EUR')
  expect(store(page).currencyReads).toBe(1)
  // Keyboard focus remains inside the modal sidebar.
  await page.getByRole('tab', { name: 'Converter' }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Close sidebar' })).toBeFocused()
  await page.getByRole('button', { name: 'Close sidebar' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Open sidebar' })).toHaveAttribute('aria-expanded', 'false')
  await openConverter(page)
  await expect(page.getByLabel('USD amount')).toHaveValue('220.12345678')
})

test('edge swipes open and close, short drags settle, and vertical scrolling still works', async ({ page, context, isMobile }) => {
  await page.setViewportSize({ width: 375, height: 700 })
  await page.goto('/')
  const menu = page.locator('.app-header button').first()
  const drawer = page.getByRole('dialog', { name: 'Tools', exact: true })
  await expect(menu).toBeEnabled()
  await swipe(page, context, isMobile, { x: 5, y: 180 }, { x: 285, y: 180 })
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByLabel('USD amount')).toBeVisible()
  await expect.poll(() => page.locator('.sidebar-panel').evaluate(node => Math.round(node.getBoundingClientRect().x))).toBe(0)
  const content = page.getByRole('tabpanel', { name: 'Converter', exact: true })
  await swipe(page, context, isMobile, { x: 310, y: 510 }, { x: 310, y: 230 })
  if (isMobile) await expect.poll(() => content.evaluate(node => node.scrollTop)).toBeGreaterThan(20)
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await swipe(page, context, isMobile, { x: 180, y: 30 }, { x: 140, y: 30 }, 400)
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await expect.poll(() => page.locator('.sidebar-panel').evaluate(node => Math.round(node.getBoundingClientRect().x))).toBe(0)
  await swipe(page, context, isMobile, { x: 220, y: 30 }, { x: 5, y: 30 })
  await expect(drawer).toHaveCount(0)
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  // A short opening drag returns to closed without activating the calendar beneath it.
  await swipe(page, context, isMobile, { x: 5, y: 180 }, { x: 45, y: 180 }, 400)
  await expect(drawer).toHaveCount(0)
  await openConverter(page)
  await page.mouse.click(370, 400)
  await expect(drawer).toHaveCount(0)
})

test('currency loading and failure do not block the budget', async ({ page }) => {
  await page.route('**/api/currencies', route => route.fulfill({ status: 503, json: { error: 'Currencies are unavailable.' } }))
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'New entry', exact: true })).toBeEnabled()
  await openConverter(page)
  await expect(page.getByRole('dialog', { name: 'Tools', exact: true }).getByRole('alert')).toHaveText('Currencies are unavailable.')
  await page.getByRole('button', { name: 'Close sidebar' }).click()
  await page.getByRole('button', { name: 'New entry', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'New entry', exact: true })).toBeVisible()
})
